#!/usr/bin/env python3
"""Build the generic prompts, and the generated parts of the docs, from the skill.

Usage:
    build_prompts.py            write the generated files
    build_prompts.py --check    exit 1 if any generated file is out of date

The skill folder is the single source for the method: rules, rubric, phase
instructions, templates and checklist cards. This script assembles them into

    prompts/full-review-prompt.md            the whole method, with the core cards
                                             and an index of the other cards by folder
    prompts/phase-prompts/NN-<phase>.md      one prompt per phase, for chaining
    .../references/checklists/INDEX.md       the top level of the card index the skill
                                             reads in Phase 1: the core cards, and every
                                             other folder with the names of its cards
    .../references/checklists/<folder>/INDEX.md
                                             the second level: every card in the folder
                                             and when it applies

and refreshes the blocks marked GENERATED in METHODOLOGY.md.

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "plugin" / "skills" / "open-paper-reviewer"
REFERENCES = SKILL / "references"
PROMPTS = ROOT / "prompts"
GENERATED_NOTE = "<!-- Generated by scripts/build_prompts.py from plugin/skills/open-paper-reviewer. Do not edit by hand. -->"
CHECKLISTS = REFERENCES / "checklists"
CARD_URL = "https://github.com/sinkomr/OpenPaperReviewer/blob/main/plugin/skills/open-paper-reviewer/references/checklists/"

# What the person pastes in for each phase when chaining the phase prompts.
PHASE_INPUTS = {
    "00": ["the paper, and any supplementary material"],
    "01": ["the paper", "`00_extraction.md`"],
    "02": ["the paper", "`00_extraction.md`", "`01_checklist_and_references.md`"],
    "03": ["the paper", "`00_extraction.md`", "`01_checklist_and_references.md`", "`02_claims_registry.md`"],
    "04": ["the paper", "`01_checklist_and_references.md`", "`02_claims_registry.md`", "the Phase 3 scrutiny files"],
    "05": ["the paper", "`00_extraction.md`", "`01_checklist_and_references.md`", "`02_claims_registry.md`", "the Phase 3 scrutiny files", "the Phase 4 reference files"],
    "06": ["`run.json` as it stands", "`02_claims_registry.md`", "the Phase 3 scrutiny files", "the Phase 4 reference files", "`05_methods.md`"],
    "07": ["the paper", "every output of phases 0 to 6"],
}

LABELS = {
    "verdict": "Verdict",
    "severity": "Severity",
    "confidence": "Confidence",
    "tier": "Tier",
    "claim_type": "Claim type",
    "access": "Access level for a source",
    "citation_status": "Status of a source",
    "citation_error": "Kind of error found in a citation",
    "citation_verdict": "Verdict on a citation (reference deep-dives)",
    "verification": "Citation verification for the whole review",
    "mode": "Review mode",
    "intake": "Intake",
    "value_source": "Where a recorded value came from",
    "method_entry": "How the method was run",
    "review_status": "Status of a posted review",
}
LIMIT_LABELS = {
    "claim_quote_words": "Quotation of a claim from the paper",
    "citation_quote_words": "Quotation from an outside source",
    "summary_words": "One-line summary of a claim's verdict",
    "claim_block_words": "Scrutiny block for an ordinary claim",
    "headline_claim_block_words": "Scrutiny block for a headline or tier-3 claim",
}


def read(path):
    return path.read_text(encoding="utf-8").strip() + "\n"


def version():
    return json.loads((ROOT / "plugin" / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]


def demote(markdown, levels=1):
    """Push every heading down so the text nests under a section of the prompt."""
    out, fenced = [], False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
        if not fenced and re.match(r"^#{1,5} ", line):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out).strip() + "\n"


def render_rubric(rubric, level=3):
    head = "#" * level
    lines = []
    for key, label in LABELS.items():
        lines.append(f"{head} {label}\n")
        for entry in rubric[key]:
            name = f"{entry['value']} ({entry['name']})" if "name" in entry else str(entry["value"])
            lines.append(f"- **{name}**: {entry['definition']}")
        lines.append("")
    lines.append(f"{head} Limits\n")
    for key, label in LIMIT_LABELS.items():
        lines.append(f"- {label}: at most {rubric['limits'][key]} words")
    lines.append("")
    lines.append(f"{head} Rules\n")
    for number, rule in enumerate(rubric["rules"], 1):
        lines.append(f"{number}. {rule}")
    return "\n".join(lines).strip() + "\n"


def card_text(path):
    text = read(path)
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
    meta = dict(line.split(":", 1) for line in match.group(1).splitlines())
    body = match.group(2).strip()
    body = re.sub(r"^# .*\n", "", body, count=1).strip()
    header = f"### Card {meta['id'].strip()}: {meta['name'].strip()}\n\nApplies when: {meta['applies_when'].strip()}\n"
    return header + "\n" + demote(body, 2)


NOT_CARDS = ("README.md", "INDEX.md")


def cards(folder):
    directory = CHECKLISTS / folder
    return [card_text(path) for path in sorted(directory.glob("*.md")) if path.name not in NOT_CARDS] if directory.is_dir() else []


def card_meta(path):
    match = re.match(r"^---\n(.*?)\n---\n", read(path), re.DOTALL)
    return {key.strip(): value.strip().strip('"') for key, value in (line.split(":", 1) for line in match.group(1).splitlines())}


# The card index has two levels, so that a review reads only what it needs. The top level
# lists the core cards and every other folder with the names of its cards; each folder's own
# INDEX.md gives every card's applies_when line. Physics is the only field so far, so the top
# level lists its subfields directly. Once other fields are added, a third level (fields, then
# subfields, then cards) may be needed to keep the top level short.

def folders_of_cards():
    """Every folder that holds cards, with its card files: core first, then the rest by field and title."""
    folders = {}
    for path in sorted(CHECKLISTS.rglob("*.md")):
        if path.name not in NOT_CARDS:
            folders.setdefault(path.parent.relative_to(CHECKLISTS).as_posix(), []).append(path)
    order = sorted(folders, key=lambda name: (name != "core", name.split("/", 1)[0], folder_title(name)))
    return {name: sorted(folders[name], key=lambda path: card_meta(path)["name"].casefold()) for name in order}


def folder_title(folder):
    """The heading of the folder's README.md, or the folder's path if it has none."""
    readme = CHECKLISTS / folder / "README.md"
    match = re.search(r"^# (.+)$", read(readme), re.MULTILINE) if readme.is_file() else None
    return match.group(1).strip() if match else folder


def link(relative, link_base=None):
    return f"[{relative}]({link_base or ''}{relative})"


def top_index(link_base=None, include_core=True):
    """Level one: the core cards, then every other folder, by field, with the names of its cards."""
    folders = folders_of_cards()
    lines = []
    if include_core and "core" in folders:
        lines += ["## Core cards: always used\n", "| Id | Card | File |", "|---|---|---|"]
        for path in folders["core"]:
            meta = card_meta(path)
            lines.append(f"| {meta['id']} | {meta['name']} | {link(path.relative_to(CHECKLISTS).as_posix(), link_base)} |")
        lines.append("")
    field = None
    for folder, paths in folders.items():
        if folder == "core":
            continue
        if folder.split("/", 1)[0] != field:
            field = folder.split("/", 1)[0]
            lines.append(f"## {folder_title(field)}\n")
        names = "; ".join(card_meta(path)["name"] for path in paths)
        lines.append(f"### {folder_title(folder)}\n")
        lines.append(f"{len(paths)} cards, index {link(folder + '/INDEX.md', link_base)}: {names}\n")
    return "\n".join(lines).strip() + "\n"


def index_file():
    folders = folders_of_cards()
    count = sum(len(paths) for paths in folders.values())
    return (
        "# Index of checklist cards\n\n"
        f"{GENERATED_NOTE}\n\n"
        f"{count} cards in {len(folders)} folders. Phase 1 uses every core card, plus every other card whose \"Applies when\" "
        "line matches the paper. To find those:\n\n"
        "1. Read the list of folders below, with the names of the cards in each.\n"
        "2. Read the index of every folder with a card whose name could apply to the paper: its field, a technique in its "
        "methods, or a kind of claim it makes. A paper often draws on more than one folder.\n"
        "3. In each folder index, select the cards whose \"Applies when\" line matches the paper, and open only those.\n\n"
        "Paths are relative to this folder. The card format is in `README.md`.\n\n"
        + top_index()
    )


def folder_index(folder, paths):
    """Level two: every card in one folder, its type and when it applies."""
    back = "../" * len(folder.split("/")) + "INDEX.md"
    lines = [
        f"# {folder_title(folder)}: index of cards\n",
        f"{GENERATED_NOTE}\n",
        f"{len(paths)} cards in `{folder}/`. Select every card whose \"Applies when\" line matches the paper, and open only "
        f"those. Paths are relative to this folder. The index of all folders is {link(back)}.\n",
        "| Id | Card | Type | Applies when | File |",
        "|---|---|---|---|---|",
    ]
    for path in paths:
        meta = card_meta(path)
        lines.append(f"| {meta['id']} | {meta['name']} | {meta['type']} | {meta['applies_when']} | {link(path.name)} |")
    return "\n".join(lines) + "\n"


def templates_named_in(text, templates):
    return [name for name in templates if f"`{name}`" in text]


def phase_title(text):
    return re.match(r"^# (.*)$", text, re.MULTILINE).group(1)


HEADER = """# OpenPaperReviewer: {title}

{note}

Method version {version}. Source and licence: https://github.com/sinkomr/OpenPaperReviewer (MIT License).

You are going to review a scientific paper with the OpenPaperReviewer method: every claim quoted, checked four ways and given a verdict from a fixed rubric, with the review's own citations verified before anything is delivered.
"""

RUN_DETAILS = """## Details of this run

The person running the review fills these in. They go into the run record.

- Paper: (attached, or pasted below)
- Model identifier:
- Reasoning effort setting (write "none exposed" if the tool has no such setting):
- Tool and version:
- Web access in this session: yes / no
- GitHub handle of the person running the review (only needed to post it):

If the model identifier or the reasoning effort is blank, ask for it before you begin. Do not fill either in from your own impression of what you are. Record them as supplied by the user.

If the tool or its version is blank, ask for it in the same message. If it is still not given, record the version as `unknown`.

Before you begin, check that the paper reached you in full. If you cannot see its text, or cannot see its figures, say so and ask for a readable copy. Never review from the title, the abstract or memory.
"""

OUTPUT_FORMAT = """## How to produce the output

The phases name output files such as `00_extraction.md`. If you can create files, write each one. If you cannot, output each document in full under a heading that is its file name, so that it can be saved as that file.

Work one phase at a time, in order. After each phase, stop and wait for the word "continue", unless you have been told to run straight through. Do not skip a phase, and do not merge two phases into one.

At the end of Phase 7, output four final documents, each in its own code block under its file name: `run.json`, `prompt.md`, `claims.json` and `citations.json`. In `prompt.md`, the Method section reads "Generic prompt `{file}` from OpenPaperReviewer {version}, unmodified", unless these instructions were changed, in which case say so and include the changed text.

If you have no way to open web pages, say so at the start, mark every outside source as unverified, and set the citation-verification line to `none`. Do not describe anything you are recalling as checked.
"""


def full_prompt(file_name, title, card_folders):
    rubric = json.loads(read(REFERENCES / "rubric.json"))
    parts = [
        HEADER.format(title=title, note=GENERATED_NOTE, version=version()),
        RUN_DETAILS,
        OUTPUT_FORMAT.format(file=file_name, version=version()),
        "## Rules\n\n" + demote(re.sub(r"^# .*\n", "", read(REFERENCES / "rules.md"), count=1).strip(), 2),
        "## Rubric\n\nEvery value below is used in its exact words.\n\n" + render_rubric(rubric),
        "## Phases\n",
    ]
    for path in sorted((REFERENCES / "phases").glob("*.md")):
        parts.append(demote(read(path), 2))
    parts.append("## Templates\n")
    for path in sorted((REFERENCES / "templates").glob("*.md")):
        parts.append(demote(read(path), 2))
    parts.append(
        "## Checklist cards\n\nPhase 1 builds the checklist from these. Use every core card below. The index after them lists "
        "every other folder of cards in the OpenPaperReviewer repository, with the names of the cards in each. For each folder "
        "with a card whose name could apply to the paper, open the folder's index at its link: it gives each card's "
        "\"Applies when\" line. If a card's line matches the paper, open the card from that index, or ask the person running "
        "the review to paste it in. If the paper uses a technique that has no card, follow the Phase 1 instructions for a "
        "technique without a card.\n"
    )
    for folder in card_folders:
        parts.extend(cards(folder))
    parts.append("## Index of card folders\n\n" + demote(top_index(CARD_URL, include_core=False), 1))
    return "\n".join(part.strip() + "\n" for part in parts)


def phase_prompt(path):
    number = path.name[:2]
    text = read(path)
    rubric = json.loads(read(REFERENCES / "rubric.json"))
    templates = {p.stem: p for p in sorted((REFERENCES / "templates").glob("*.md"))}
    title = phase_title(text)
    parts = [
        HEADER.format(title=f"{title} (single-phase prompt)", note=GENERATED_NOTE, version=version()),
        f"This prompt covers one phase only: {title}. Do this phase and nothing else, then stop.\n",
        "## What you will be given\n\n" + "\n".join(f"- {item}" for item in PHASE_INPUTS[number]) + "\n\n"
        "If any of these is missing, ask for it before you begin.\n",
    ]
    if number == "00":
        parts.append(RUN_DETAILS)
    parts.append(
        "## How to produce the output\n\nIf you can create files, write the output files this phase names. If you cannot, "
        "output each document in full under a heading that is its file name, so that it can be saved as that file. "
        "If you have no way to open web pages, say so, and mark every outside source as unverified.\n"
    )
    parts.append("## Rules\n\n" + demote(re.sub(r"^# .*\n", "", read(REFERENCES / "rules.md"), count=1).strip(), 2))
    parts.append("## Rubric\n\nEvery value below is used in its exact words.\n\n" + render_rubric(rubric))
    parts.append("## Instructions for this phase\n\n" + demote(text, 2))
    used = templates_named_in(text, templates)
    if number == "07":
        used = sorted(set(used) | {"run-record"})
    if used:
        parts.append("## Templates used in this phase\n")
        parts.extend(demote(read(templates[name]), 2) for name in used)
    if number == "01":
        parts.append(
            "## Checklist cards\n\nUse every core card below. The index after them lists every other folder of cards in the "
            "OpenPaperReviewer repository, with the names of the cards in each. For each folder with a card whose name could "
            "apply to the paper, open the folder's index at its link: it gives each card's \"Applies when\" line. If a card's "
            "line matches the paper, open the card from that index, or ask for it to be pasted in. For a technique with no "
            "card, follow the instructions above for a technique without a card.\n"
        )
        parts.extend(cards("core"))
        parts.append("## Index of card folders\n\n" + demote(top_index(CARD_URL, include_core=False), 1))
    return "\n".join(part.strip() + "\n" for part in parts)


def refresh_blocks(text, blocks):
    for name, content in blocks.items():
        pattern = re.compile(rf"(<!-- BEGIN GENERATED: {name} -->\n)(.*?)(<!-- END GENERATED: {name} -->)", re.DOTALL)
        if not pattern.search(text):
            sys.exit(f"build_prompts: METHODOLOGY.md has no GENERATED block named {name!r}")
        text = pattern.sub(lambda match: match.group(1) + content.strip() + "\n" + match.group(3), text)
    return text


def phases_table():
    rows = ["| Phase | What it does |", "|---|---|"]
    for path in sorted((REFERENCES / "phases").glob("*.md")):
        text = read(path)
        purpose = re.search(r"^Purpose: (.*)$", text, re.MULTILINE).group(1)
        rows.append(f"| {phase_title(text).replace('Phase ', '')} | {purpose[0].upper()}{purpose[1:]} |")
    return "\n".join(rows) + "\n"


def build():
    outputs = {
        PROMPTS / "full-review-prompt.md": full_prompt("full-review-prompt.md", "full review prompt", ["core"]),
        CHECKLISTS / "INDEX.md": index_file(),
    }
    for folder, paths in folders_of_cards().items():
        if folder != "core":
            outputs[CHECKLISTS / folder / "INDEX.md"] = folder_index(folder, paths)
    for path in sorted((REFERENCES / "phases").glob("*.md")):
        outputs[PROMPTS / "phase-prompts" / path.name] = phase_prompt(path)
    methodology = ROOT / "METHODOLOGY.md"
    if methodology.is_file():
        rubric = json.loads(read(REFERENCES / "rubric.json"))
        blocks = {"rubric": render_rubric(rubric, level=3), "rules": demote(re.sub(r"^# .*\n", "", read(REFERENCES / "rules.md"), count=1).strip(), 0), "phases": phases_table()}
        outputs[methodology] = refresh_blocks(methodology.read_text(encoding="utf-8"), blocks)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    outputs = build()
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    expected = {path for path in outputs if PROMPTS in path.parents}
    extra = [path.relative_to(ROOT) for path in PROMPTS.rglob("*.md") if path not in expected and path.name != "README.md"] if PROMPTS.is_dir() else []
    extra += [path.relative_to(ROOT) for path in CHECKLISTS.rglob("INDEX.md") if path not in outputs]
    if args.check:
        for path in stale:
            print(f"out of date: {path}")
        for path in extra:
            print(f"not generated by this script: {path}")
        if stale or extra:
            sys.exit("Run: python3 scripts/build_prompts.py")
        print(f"{len(outputs)} generated file(s) are up to date")
    else:
        for path in extra:
            print(f"warning: {path} is not generated by this script")
        print(f"wrote {len(stale)} file(s); {len(outputs) - len(stale)} already up to date")


if __name__ == "__main__":
    main()
